/**
 * Build the single-file Client bundle served to the DSH Web client.
 *
 * The Client half is split by domain under `src/client/`, but it is *not* an
 * ESM graph: every part intentionally shares one factory scope, so the build
 * concatenates the parts in a fixed order inside the DSH module factory.
 *
 * - UI: React + TypeScript + Radix + Lucide + Tailwind (esbuild bundle).
 * - Client logic: TypeScript/TSX domain parts transformed then concatenated.
 * - `lib/client.js` is a build artifact; never edit it by hand.
 *
 * Run: node scripts/build.mjs (or node scripts/build-client.mjs)
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build, transform } from 'esbuild'
import postcss from 'postcss'
import tailwindcss from 'tailwindcss'
import autoprefixer from 'autoprefixer'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const clientDir = join(root, 'src', 'client')
const uiDir = join(clientDir, 'ui')
const outPath = join(root, 'lib', 'client.js')

// The page runtime is produced by scripts/build-runtime.mjs. The Client embeds
// the built artifact as a string and injects it into the embedded page.
const runtimePath = join(root, 'lib', 'runtime.js')
if (!existsSync(runtimePath)) {
  throw new Error('missing ' + runtimePath + ' — run scripts/build-runtime.mjs first (npm run build:runtime)')
}
const pageRuntimeSource = await readFile(runtimePath, 'utf8')

/**
 * Ordered Client parts. The order is the shared-scope execution order:
 * constants/store/remote/theme/history/prompt first, then shared primitives,
 * then domain parts, then bootstrap registrations last.
 */
const PARTS = [
  ['platform/constants.ts', 'ts'],
  ['platform/store.ts', 'ts'],
  ['platform/remote.ts', 'ts'],
  ['platform/theme.ts', 'ts'],
  ['platform/history.ts', 'ts'],
  ['platform/prompt.ts', 'ts'],
  ['shared/utils.ts', 'ts'],
  ['shared/primitives.ts', 'ts'],
  ['domains/persistence/sync-queue.ts', 'ts'],
  ['domains/persistence/source-hints.ts', 'ts'],
  ['domains/workspace/git-store.ts', 'ts'],
  ['domains/workspace/git-panel.tsx', 'tsx'],
  ['domains/carrier/carrier.ts', 'ts'],
  ['domains/annotation/clip-store.ts', 'ts'],
  ['domains/annotation/clip-tray.tsx', 'tsx'],
  ['domains/inspector/dom-tree.tsx', 'tsx'],
  ['domains/inspector/body.tsx', 'tsx'],
  ['domains/browser/browser-entry.tsx', 'tsx'],
  ['domains/settings/section.tsx', 'tsx'],
  ['platform/bootstrap/register.tsx', 'tsx'],
]

const localeZhRaw = JSON.parse(await readFile(join(root, 'locale', 'zh.json'), 'utf8'))
const localeEnRaw = JSON.parse(await readFile(join(root, 'locale', 'en.json'), 'utf8'))
function flattenLocale(source, prefix = '', out = {}) {
  for (const [key, value] of Object.entries(source)) {
    const path = prefix === '' ? key : prefix + '.' + key
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) flattenLocale(value, path, out)
    else out[path] = value
  }
  return out
}
const localeZh = flattenLocale(localeZhRaw)
const localeEn = flattenLocale(localeEnRaw)

const uiBuild = await build({
  entryPoints: [join(uiDir, 'entry.tsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react', 'react/jsx-runtime'],
  jsx: 'transform',
  logLevel: 'silent',
})
const uiCode = uiBuild.outputFiles[0].text
const tailwindConfig = (await import(join(root, 'tailwind.config.cjs'))).default
const postcssResult = await postcss([
  tailwindcss({ config: tailwindConfig }),
  autoprefixer,
]).process(await readFile(join(uiDir, 'styles.css'), 'utf8'), {
  from: join(uiDir, 'styles.css'),
})
const uiCss = postcssResult.css

const pieces = []
for (const [part, loader] of PARTS) {
  const path = join(clientDir, part)
  if (!existsSync(path)) throw new Error('missing client part: ' + path)
  const compiled = await transform(await readFile(path, 'utf8'), {
    loader,
    target: 'es2020',
    jsx: 'transform',
    legalComments: 'none',
  })
  pieces.push('/* ---- ' + part + ' ---- */\n' + compiled.code.trim())
}

await mkdir(join(root, 'lib'), { recursive: true })

